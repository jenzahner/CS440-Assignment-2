"""Turns hw2.ipynb into the two modules the tests import, and runs the example
checks. Used by check() in the notebook, by check.py, and for grading.
Do not edit this file; the grader uses its own copy.

The rule (stated at the top of hw2.ipynb): every code cell whose first non-empty
line is "# GRADED: hw2" or "# GRADED: answers" is graded. The cells of each
kind are joined, top to bottom, after a fixed preamble of imports, into hw2.py
and answers.py. All other cells are ignored.
"""
import datetime
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

MARKER = re.compile(r"^#\s*GRADED\s*:\s*(\w+)\s*$", re.IGNORECASE)
PREAMBLES = {
    "hw2": "import math\n\nimport torch\nfrom torch import nn\n",
    "answers": "import math\n",
}
LIB = os.path.dirname(os.path.abspath(__file__))
NOTE_ANSWERS = "Only the format of the answers is checked here."


def cell_source(cell):
    src = cell.get("source", "")
    return "".join(src) if isinstance(src, list) else str(src)


def _clean(source):
    """Replace notebook-only lines (%magic, !shell) with `pass`, keeping indentation."""
    out = []
    for line in source.splitlines():
        stripped = line.lstrip()
        if stripped.startswith(("%", "!")):
            line = line[:len(line) - len(stripped)] + "pass  # notebook command ignored by the grader"
        out.append(line)
    return "\n".join(out)


def graded_cells(nb):
    """{module: [(cell number, first code line, source), ...]} and notes about the notebook."""
    cells = {name: [] for name in PREAMBLES}
    notes = []
    raw = nb.get("cells") if isinstance(nb, dict) else None
    if not isinstance(raw, list):
        notes.append("The file has no list of cells: it is not a Jupyter notebook.")
        raw = []
    for number, cell in enumerate(raw, start=1):
        if not isinstance(cell, dict) or cell.get("cell_type") != "code":
            continue
        source = cell_source(cell)
        first = next((line.strip() for line in source.splitlines() if line.strip()), "")
        match = MARKER.match(first)
        if match is None:
            if re.match(r"#\s*GRADED\b", first, re.IGNORECASE):
                notes.append(f"Cell {number} starts with {first!r}, which is not a valid GRADED line; "
                             f"it was ignored.")
            continue
        name = match.group(1).lower()
        if name not in cells:
            notes.append(f"Cell {number} is marked GRADED: {match.group(1)}, which is not one of "
                         f"{', '.join(PREAMBLES)}; it was ignored.")
            continue
        body = [line.strip() for line in source.splitlines() if line.strip()][1:]
        cells[name].append((number, (body[0][:60] if body else "(empty)"), _clean(source)))
    for name, found in cells.items():
        if not found:
            notes.append(f"No cell is marked '# GRADED: {name}'.")
    return cells, notes


def extract(nb, out_dir):
    """Write <module>.py into out_dir for every module that has graded cells.

    Returns (list of modules written, notes)."""
    cells, notes = graded_cells(nb)
    written = []
    for name, found in cells.items():
        if not found:
            continue
        parts = [f"# Generated from the '# GRADED: {name}' cells of the notebook.\n" + PREAMBLES[name]]
        parts += [f"# ---- notebook cell {number}: {first}\n{source}\n" for number, first, source in found]
        with open(os.path.join(out_dir, name + ".py"), "w", encoding="utf-8") as f:
            f.write("\n\n".join(parts))
        written.append(name)
    return written, notes


def location(path, lineno):
    """'notebook cell N, line K' for a line of a module written by extract(), else None."""
    try:
        with open(path, encoding="utf-8") as f:
            lines = f.read().splitlines()[:lineno]
    except OSError:
        return None
    for i in range(len(lines) - 1, -1, -1):
        match = re.match(r"# ---- notebook cell (\d+): (.*)$", lines[i])
        if match:
            return (f"line {lineno - i - 1} of the GRADED cell starting '{match.group(2)}' "
                    f"(cell {match.group(1)} of the notebook)")
    return None


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


# --------------------------------------------------------------------------
# Public checks (check() in the notebook, and check.py)

def _colab_notebook():
    """The notebook open in Google Colab, or None outside Colab."""
    try:
        from google.colab import _message  # noqa: PLC0415 - only exists in Colab
    except ImportError:
        return None
    reply = _message.blocking_request("get_ipynb", request="", timeout_sec=30)
    return reply.get("ipynb") if isinstance(reply, dict) else None


def _find_notebook(path):
    if path is not None:
        return path
    if os.path.exists("hw2.ipynb"):
        return "hw2.ipynb"
    candidates = [f for f in os.listdir(".") if f.endswith(".ipynb")]
    return candidates[0] if len(candidates) == 1 else None


def _run_group(work, group, timeout, points_max):
    cmd = [sys.executable, os.path.join(work, "hw2lib", "runner.py"), group,
           os.path.join(LIB, "public_cases.json")]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, cwd=work)
    except subprocess.TimeoutExpired:
        return {"points": 0, "max": points_max,
                "messages": [f"timed out after {timeout} s (an infinite loop, or far too slow)"]}
    from hw2lib.runner import RESULT_MARK
    for line in proc.stdout.splitlines():
        if line.startswith(RESULT_MARK):
            return json.loads(line[len(RESULT_MARK):])
    err = (proc.stderr.strip().splitlines() or ["(no output)"])[-1]
    return {"points": 0, "max": points_max, "messages": [f"crashed: {err}"]}


def check(part=None, notebook=None):
    """Test the saved notebook locally, or the open notebook in Colab, on example cases.

    part: None for everything, or one of "p1", "p2", "p3".
    Locally, save first (Ctrl+S / Cmd+S): this reads the file, not the kernel.
    An explicit notebook path always uses that file, including in Colab.
    """
    from hw2lib.grading import GROUPS, PARTS
    if part is None:
        parts = list(PARTS)
    elif part in PARTS:
        parts = [part]
    else:
        print(f"Unknown part {part!r}; use one of {', '.join(PARTS)}, or nothing for all.")
        return

    # An extracted starter zip can leave a stale hw2.ipynb beside hw2lib in Colab.
    # Prefer the open notebook unless the caller explicitly requests a file.
    nb = _colab_notebook() if notebook is None else None
    path = _find_notebook(notebook) if nb is None else None
    if nb is not None:
        print("Checking the notebook open in Colab.\n")
    elif path is not None:
        nb = load(path)
        saved = datetime.datetime.fromtimestamp(os.path.getmtime(path))
        age = (datetime.datetime.now() - saved).total_seconds()
        print(f"Checking {path} (saved at {saved:%H:%M:%S}, {age:.0f} s ago). "
              f"Save the notebook first if you have changed it.\n")
    else:
        print("Could not find hw2.ipynb in the current folder. Run this from the folder that "
              "holds hw2.ipynb and hw2lib/, or pass the path: check(notebook='path/to/hw2.ipynb').")
        return

    work = tempfile.mkdtemp(prefix="hw2-check-")
    try:
        shutil.copytree(LIB, os.path.join(work, "hw2lib"), ignore=shutil.ignore_patterns("__pycache__"))
        _, notes = extract(nb, work)
        for note in notes:
            print("note: " + note)
        if notes:
            print()
        total = maximum = 0.0
        for p in parts:
            for group in PARTS[p]:
                points_max, title, timeout = GROUPS[group]
                print(f"{title:34s} ", end="", flush=True)
                r = _run_group(work, group, timeout, points_max)
                if group.startswith("answers"):
                    print("format check only")
                else:
                    total += r["points"]
                    maximum += r["max"]
                    counts = f"  ({r['passed']}/{r['total']} cases)" if "total" in r else ""
                    print(f"{r['points']:5.2f} / {r['max']}{counts}")
                for m in r["messages"]:
                    print("    " + m)
    finally:
        shutil.rmtree(work, ignore_errors=True)
    if maximum:
        print(f"\nTotal on the code examples: {total:g} / {maximum:g}.")
    if any(g.startswith("answers") for p in parts for g in PARTS[p]):
        print(NOTE_ANSWERS)
